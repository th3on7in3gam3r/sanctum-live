/**
 * Website languages: English, Luganda and Kiswahili.
 *
 * The visitor's choice is kept in the `plcc_lang` cookie (set by the language
 * switcher). Text the church writes in Canaan (sermons, events, announcements,
 * page bodies) is shown as entered; everything the site itself says is here.
 *
 * Luganda and Kiswahili were drafted for the church; have a native speaker on
 * staff review and adjust any wording here (one file, plain text).
 */

export const LOCALES = ['en', 'lg', 'sw'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'en';
export const LOCALE_COOKIE = 'plcc_lang';

export const LOCALE_NAMES: Record<Locale, string> = { en: 'English', lg: 'Luganda', sw: 'Kiswahili' };
/** BCP-47 tag for <html lang>. */
export const LOCALE_TAGS: Record<Locale, string> = { en: 'en', lg: 'lg', sw: 'sw' };
/** Bible API language each site language prefers. */
export const LOCALE_BIBLE_LANGUAGE: Record<Locale, string> = { en: 'eng', lg: 'lug', sw: 'swh' };

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value);
}

