const DICTS: Record<Locale, Dict> = { en, lg, sw };

export function dictionary(locale: Locale): Dict {
  return DICTS[locale] ?? en;
}

/** A label from the shared nav lists, translated when we know it. */
export function label(t: Dict, english: string): string {
  return t.labels[english] ?? english;
}

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? '');
}
